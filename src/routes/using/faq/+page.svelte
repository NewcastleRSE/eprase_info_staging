<details class="faq-item">
	<summary class="question">
		<span class="q-prefix">Q:</span> Why am I unable to access the tool using my nhs.uk domain?
	</summary>

    <div class="answer-content"><p class="answer">
		<span class="a-prefix">A:</span> The tool can only be accessed currently from within an NHS network (HSCN), to users with nhs.net or nhs.uk email accounts. There is no 'public' access from anywhere (unless you are connected to your NHS network remotely). This means that unless you have remote access set up from a device you cannot use at home, access will be limited to inside your work locations. If you are at a work location and still unable to get access, you will need to log a ticket with your IT support team and get them to check if there is a firewall blocking the domain. Home Nations not on the HSCN are unable to use the tool. We are working on a solution, please bear with us.</p>
    </div>
</details>

<details class="faq-item">
	<summary class="question">
		<span class="q-prefix">Q:</span>Why is the tool hosted on the HSCN?
	</summary>

    <div class="answer-content"><p class="answer">
		<span class="a-prefix">A:</span>The NHS-sponsored ePRaSE tool is hosted on the Health and Social Care Network (HSCN), a secure infrastructure specifically designed to safeguard sensitive patient information and mitigate cyber threats. In light of the increased risk of cyberattacks targeting healthcare and other critical national services, it has been determined that it will be safer for Trusts for the tool to continue to be hosted on HSCN. Consequently, we are reviewing mechanisms to enable home nations to access HSCN for the purpose of completing the assessment.</p>
	</div>
</details>

