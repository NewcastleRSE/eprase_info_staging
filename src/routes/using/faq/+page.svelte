<details class="faq-item">
	<summary class="question">
		<span class="q-prefix">Q:</span> Do we have to admit in Patient Administration System (PAS)? Or can we admit manually in the EPMA system directly as this is easier for us to manage locally?
	</summary>

    <div class="answer-content"><p class="answer">
		<span class="a-prefix">A:</span> We recommend following your normal operating procedure. If patient information is drawn from PAS into the electronic prescribing system normally, we would recommend that you do that. Some patients require additional clinical or general information such as GP name to be added for the scenarios/test to work correctly. Please use whatever standard dummy information you would normally use to test your systems. We estimate it takes 1-2 hours to set up the fictional patients and similar time to run the test part and record observations. You can log in and out of the patient build sections without losing your place so that it can be completed over several different sessions if that is easier.</p>
	</div>
</details>

